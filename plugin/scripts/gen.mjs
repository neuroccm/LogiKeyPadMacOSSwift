// Generates plugin action definitions + key-face SVGs from the single
// source of truth: Sources/LogiKeyPad/Resources/catalog.json.
// Theme: --theme=midnight|blueprint, else the app's saved theme, else midnight.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pluginRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = join(pluginRoot, '..', 'Sources', 'LogiKeyPad', 'Resources', 'catalog.json');
const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));

const THEMES = { midnight: '#000000', blueprint: '#052ED9' };
function pickTheme() {
  const flag = process.argv.find((a) => a.startsWith('--theme='));
  if (flag) return flag.split('=')[1];
  const saved = join(homedir(), 'Library', 'Application Support', 'LogiKeyPad', 'theme.txt');
  if (existsSync(saved)) {
    const t = readFileSync(saved, 'utf8').trim();
    if (THEMES[t]) return t;
  }
  return 'midnight';
}
const themeName = pickTheme();
const bg = THEMES[themeName] ?? THEMES.midnight;

// action id -> page title (becomes the Options+ group/folder)
const groupOf = new Map();
for (const page of catalog.pages) for (const id of page.keys) groupOf.set(id, page.title);

// Direct-exec fallback used only when the Swift app is not running,
// so agent-launcher keys are never dead. Everything else needs the app.
function fallbackFor(a) {
  if (a.kind === 'openApp') return `open -a ${JSON.stringify(a.arg)}`;
  return null;
}

const defs = catalog.actions.map((a) => ({
  id: a.id,
  title: a.title,
  sub: a.sub,
  group: groupOf.get(a.id) ?? 'Dev Pad',
  fallback: fallbackFor(a),
}));

writeFileSync(
  join(pluginRoot, 'src', 'catalog.generated.ts'),
  `// GENERATED by scripts/gen.mjs — do not edit. Source: catalog.json (theme: ${themeName}).\n` +
    `export interface ActionDef { id: string; title: string; sub: string; group: string; fallback: string | null }\n` +
    `export const ACTIONS: ActionDef[] = ${JSON.stringify(defs, null, 2)};\n`
);

// Key faces: full-bleed themed rounded square, white label. Sans-serif
// text only — no icon-font dependency on the device rasterizer.
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function svgFor(a) {
  const titleSize = a.title.length > 7 ? 16 : a.title.length > 5 ? 19 : 23;
  const sub = a.sub
    ? `<text x="48" y="66" font-family="Helvetica, Arial, sans-serif" font-size="11" fill="#FFFFFF" fill-opacity="0.75" text-anchor="middle">${esc(a.sub)}</text>`
    : '';
  const titleY = a.sub ? 46 : 56;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96">` +
    `<rect x="2" y="2" width="92" height="92" rx="16" fill="${bg}"/>` +
    `<rect x="2" y="2" width="92" height="92" rx="16" fill="none" stroke="#FFFFFF" stroke-opacity="0.25"/>` +
    `<text x="48" y="${titleY}" font-family="Helvetica, Arial, sans-serif" font-size="${titleSize}" font-weight="700" fill="#FFFFFF" text-anchor="middle">${esc(a.title)}</text>` +
    sub +
    `</svg>\n`;
}

for (const dir of ['package/actionicons', 'package/actionsymbols']) {
  const abs = join(pluginRoot, dir);
  mkdirSync(abs, { recursive: true });
  for (const a of catalog.actions) writeFileSync(join(abs, `${a.id}.svg`), svgFor(a));
}

console.log(`gen: ${defs.length} actions, theme=${themeName} (${bg}), catalog v${catalog.version}`);
